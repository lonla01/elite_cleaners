// Builds src/content/geo/cantons.ts: simplified SVG paths for Luxembourg's 12 cantons.
// Data © OpenStreetMap contributors, available under the Open Database Licence (ODbL).
// The site shows this attribution under the map. Run manually; the output is committed.
// Usage: node scripts/build-canton-map.mjs
import { writeFileSync } from "node:fs";

const WIDTH = 400;
const TOLERANCE = 0.6; // Douglas-Peucker tolerance, in output pixels

// OSM relation ids of the cantons (boundary=administrative, admin_level=6, ISO3166-2=LU-*).
const relations = {
  407792: "Echternach",
  407796: "Grevenmacher",
  407799: "Remich",
  407810: "Mersch",
  407813: "Capellen",
  407824: "Luxembourg",
  660245: "Redange",
  1113683: "Diekirch",
  1113898: "Esch-sur-Alzette",
  1115796: "Clervaux",
  1115797: "Wiltz",
  1342842: "Vianden",
};

// Fetch each relation with its ways and nodes from the main OSM API.
async function fetchRelation(id) {
  const res = await fetch(`https://api.openstreetmap.org/api/0.6/relation/${id}/full.json`, {
    headers: { "User-Agent": "elite-cleaners-map-build/1.0" },
  });
  if (!res.ok) throw new Error(`OSM API ${id}: ${res.status}`);
  const { elements } = await res.json();
  const nodes = new Map(
    elements.filter((e) => e.type === "node").map((n) => [n.id, [n.lon, n.lat]]),
  );
  const ways = new Map(elements.filter((e) => e.type === "way").map((w) => [w.id, w.nodes]));
  const rel = elements.find((e) => e.type === "relation" && e.id === Number(id));
  return {
    members: rel.members
      .filter((m) => m.type === "way")
      .map((m) => ({ ...m, geometry: ways.get(m.ref).map((n) => nodes.get(n)) })),
  };
}

// Join outer ways into closed rings.
function rings(rel) {
  const ways = rel.members
    .filter((m) => m.type === "way" && m.role === "outer")
    .map((m) => m.geometry);
  const key = (p) => p.join(",");
  const out = [];
  while (ways.length) {
    let ring = ways.shift();
    while (key(ring[0]) !== key(ring.at(-1))) {
      const i = ways.findIndex(
        (w) => key(w[0]) === key(ring.at(-1)) || key(w.at(-1)) === key(ring.at(-1)),
      );
      if (i === -1) break;
      const [w] = ways.splice(i, 1);
      ring = ring.concat(key(w[0]) === key(ring.at(-1)) ? w.slice(1) : w.reverse().slice(1));
    }
    out.push(ring);
  }
  return out;
}

const all = [];
for (const [id, name] of Object.entries(relations)) {
  all.push({ name, rings: rings(await fetchRelation(id)) });
}
const pts = all.flatMap((c) => c.rings.flat());
const minLon = Math.min(...pts.map((p) => p[0]));
const maxLon = Math.max(...pts.map((p) => p[0]));
const minLat = Math.min(...pts.map((p) => p[1]));
const maxLat = Math.max(...pts.map((p) => p[1]));
const midLat = ((minLat + maxLat) / 2) * (Math.PI / 180);
const scale = WIDTH / ((maxLon - minLon) * Math.cos(midLat));
const HEIGHT = Math.round((maxLat - minLat) * scale);
const project = ([lon, lat]) => [(lon - minLon) * Math.cos(midLat) * scale, (maxLat - lat) * scale];

function simplify(points, tol) {
  if (points.length < 3) return points;
  let maxD = 0;
  let index = 0;
  const [a, b] = [points[0], points.at(-1)];
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    const d = Math.abs(dy * x - dx * y + b[0] * a[1] - b[1] * a[0]) / len;
    if (d > maxD) [maxD, index] = [d, i];
  }
  if (maxD <= tol) return [a, b];
  return simplify(points.slice(0, index + 1), tol)
    .slice(0, -1)
    .concat(simplify(points.slice(index), tol));
}

// A closed ring starts and ends on the same point, which defeats Douglas-Peucker; simplify
// the two halves separately.
function simplifyRing(ring, tol) {
  const mid = Math.floor(ring.length / 2);
  return simplify(ring.slice(0, mid + 1), tol).concat(simplify(ring.slice(mid), tol).slice(1));
}

const r = (n) => Math.round(n * 10) / 10;
const cantons = all
  .map(({ name, rings }) => ({
    id: name
      .normalize("NFD")
      .replace(/\p{Diacritic}/gu, "")
      .toLowerCase()
      .replace(/[^a-z]+/g, "-"),
    name,
    d: rings
      .map((ring) => simplifyRing(ring.map(project), TOLERANCE))
      .filter((ring) => ring.length > 3)
      .map((ring) => "M" + ring.map(([x, y]) => `${r(x)} ${r(y)}`).join("L") + "Z")
      .join(""),
  }))
  .sort((a, b) => a.id.localeCompare(b.id));

const bounds = { minLon, maxLon, minLat, maxLat, midLat, scale };
writeFileSync(
  "src/content/geo/cantons.ts",
  `// GENERATED by scripts/build-canton-map.mjs. Do not edit by hand.
// Boundary data © OpenStreetMap contributors, ODbL (https://www.openstreetmap.org/copyright).

export const mapSize = { width: ${WIDTH}, height: ${HEIGHT} } as const;

/** Equirectangular projection used for the paths, for placing commune markers. */
const bounds = ${JSON.stringify(bounds)};

export function projectToMap(lat: number, lon: number): [number, number] {
  return [
    Math.round((lon - bounds.minLon) * Math.cos(bounds.midLat) * bounds.scale * 10) / 10,
    Math.round((bounds.maxLat - lat) * bounds.scale * 10) / 10,
  ];
}

export const cantonIds = ${JSON.stringify(cantons.map((c) => c.id))} as const;
export type CantonId = (typeof cantonIds)[number];

/** Official (OSM) names; display names are translated in the content files. */
export const cantonPaths: Record<CantonId, { osmName: string; d: string }> = ${JSON.stringify(
    Object.fromEntries(cantons.map((c) => [c.id, { osmName: c.name, d: c.d }])),
    null,
    2,
  )};
`,
);
console.log(
  `Wrote ${cantons.length} cantons (${WIDTH}×${HEIGHT}).`,
  cantons.map((c) => c.id).join(", "),
);
